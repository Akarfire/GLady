async function findMemeImage(memeName)
{
    const formats = [".gif", ".png", ".jpeg", ".webp"];

    let fileBase = "../Data/" + memeName;

    let file = "";
    for (let i = 0; i < formats.length; i++)
    {
        file = fileBase + formats[i];

        let image = new Image();
        image.src = file;

        try
        {
            await image.decode();
            break;
        }

        catch {}
    }

    return file;
}

